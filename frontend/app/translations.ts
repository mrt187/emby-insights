const dictionaries: Record<Lang, Record<TranslationKey, string>> = { de, en };

export type Translate = (key: TranslationKey, vars?: Record<string, string | number>) => string;

export function t(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  let value = dictionaries[lang]?.[key] ?? de[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replace(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function isLang(value: unknown): value is Lang {
  return value === "de" || value === "en";
}

// Components read the language from context; plain helper functions take it
// as an explicit `lang` parameter instead, since hooks can't be called there.
export const LanguageContext = createContext<Lang>("en");

export function useLang(): Lang {
  return useContext(LanguageContext);
}

export function useT(): Translate {
  const lang = useContext(LanguageContext);
  return (key, vars) => t(lang, key, vars);
}

